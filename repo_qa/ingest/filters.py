"""Decide which files and folders of a repository are worth indexing.

The approach is an allow-list: only file types we know how to read are kept, so
binaries, images, archives and unknown formats are excluded automatically. On top of
that we drop dependency folders, build output, lock files, minified and generated
files, which would otherwise flood the index with noise.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import PurePosixPath

# ---- folders never worth descending into
IGNORED_DIRS = frozenset(
    {
        "node_modules", "__pycache__", "venv", "virtualenv", "site-packages",
        "dist", "build", "target", "vendor", "third_party", "bower_components",
        "coverage", "htmlcov", "_build", "bin", "obj",
    }
)
# hidden folders (".git", ".venv", ".idea", ...) are skipped too, except these
ALLOWED_HIDDEN_DIRS = frozenset({".github"})
IGNORED_DIR_SUFFIXES = (".egg-info", ".dist-info")

# ---- files never worth indexing
IGNORED_FILE_NAMES = frozenset(
    {
        "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock", "pipfile.lock",
        "cargo.lock", "go.sum", "composer.lock", "gemfile.lock", "uv.lock",
        "license", "license.md", "license.txt", "copying", "notice", "authors",
    }
)
IGNORED_FILE_SUFFIXES = (".min.js", ".min.css", ".map", "_pb2.py", "_pb2_grpc.py", ".pb.go", ".lock")

# ---- what we can read (extension -> language)
CODE_EXTENSIONS = {
    ".py": "python", ".pyi": "python",
    ".js": "javascript", ".jsx": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".ts": "typescript", ".tsx": "typescript",
    ".java": "java", ".kt": "kotlin", ".scala": "scala",
    ".go": "go", ".rs": "rust", ".rb": "ruby", ".php": "php", ".swift": "swift",
    ".c": "c", ".h": "c", ".cpp": "cpp", ".cc": "cpp", ".hpp": "cpp", ".cs": "csharp",
    ".sh": "shell", ".bash": "shell", ".sql": "sql",
    ".html": "html", ".css": "css", ".scss": "css", ".vue": "vue",
}
DOC_EXTENSIONS = {
    ".md": "markdown", ".markdown": "markdown", ".rst": "rst", ".txt": "text", ".adoc": "asciidoc",
}
CONFIG_EXTENSIONS = {
    ".json": "json", ".yaml": "yaml", ".yml": "yaml", ".toml": "toml", ".ini": "ini", ".cfg": "ini",
}
# exact (lower-cased) file names
SPECIAL_FILES = {
    "dockerfile": ("config", "dockerfile"),
    "makefile": ("config", "makefile"),
    "requirements.txt": ("config", "requirements"),
    "docker-compose.yml": ("config", "yaml"),
    "docker-compose.yaml": ("config", "yaml"),
}

# data-like files (big JSON/YAML dumps) get a much lower size limit than source code
MAX_CONFIG_BYTES = 50_000
GENERATED_MARKERS = (
    "do not edit", "auto-generated", "autogenerated", "@generated", "code generated",
    "this file was generated", "generated by the protocol buffer compiler",
)


@dataclass(frozen=True)
class FileClass:
    kind: str  # "code" | "doc" | "config"
    language: str


def should_skip_dir(name: str) -> bool:
    """True if a folder should not be entered."""
    lowered = name.lower()
    if lowered in IGNORED_DIRS or lowered.endswith(IGNORED_DIR_SUFFIXES):
        return True
    return name.startswith(".") and name not in ALLOWED_HIDDEN_DIRS


def skip_file_reason(name: str) -> str | None:
    """Return why a file name is excluded, or None if it may be indexed."""
    lowered = name.lower()
    if name.startswith("."):
        return "hidden_file"
    if lowered in IGNORED_FILE_NAMES or lowered.endswith(IGNORED_FILE_SUFFIXES):
        return "ignored_file"
    return None


def classify(name: str) -> FileClass | None:
    """Classify a file by name; None means the type is unsupported."""
    lowered = name.lower()
    special = SPECIAL_FILES.get(lowered)
    if special:
        return FileClass(*special)
    suffix = PurePosixPath(lowered).suffix
    if suffix in CODE_EXTENSIONS:
        return FileClass("code", CODE_EXTENSIONS[suffix])
    if suffix in DOC_EXTENSIONS:
        return FileClass("doc", DOC_EXTENSIONS[suffix])
    if suffix in CONFIG_EXTENSIONS:
        return FileClass("config", CONFIG_EXTENSIONS[suffix])
    return None


def size_limit(file_class: FileClass, max_file_bytes: int) -> int:
    """Largest file size accepted for this class of file."""
    if file_class.kind == "config":
        return min(MAX_CONFIG_BYTES, max_file_bytes)
    return max_file_bytes


def is_test_path(path: str) -> bool:
    """Heuristic: does this repo-relative path look like a test file?"""
    parts = PurePosixPath(path.lower()).parts
    name = parts[-1] if parts else ""
    if any(p in ("test", "tests", "__tests__", "spec", "specs", "testing") for p in parts[:-1]):
        return True
    return (
        name.startswith("test_")
        or name.endswith(("_test.py", "_test.go", ".test.js", ".test.ts", ".test.tsx", ".spec.js", ".spec.ts"))
        or name in ("conftest.py", "tests.py", "test.py")
    )


def looks_binary(sample: bytes) -> bool:
    """True if the first bytes of a file contain a NUL byte (not text)."""
    return b"\x00" in sample


def looks_generated(text: str) -> bool:
    """True if the first lines of a code file announce that it was machine-generated."""
    head = "\n".join(text.splitlines()[:5]).lower()
    return any(marker in head for marker in GENERATED_MARKERS)
