class UrlTests(unittest.TestCase):
    def test_valid_urls(self) -> None:
        cases = {
            "https://github.com/pallets/flask": ("pallets", "flask", None),
            "https://github.com/pallets/flask.git": ("pallets", "flask", None),
            "https://github.com/pallets/flask/": ("pallets", "flask", None),
            "  https://github.com/pallets/flask  ": ("pallets", "flask", None),
            "github.com/pallets/flask": ("pallets", "flask", None),
            "http://github.com/pallets/flask": ("pallets", "flask", None),
            "https://github.com/pallets/flask/tree/main": ("pallets", "flask", "main"),
            "https://github.com/o/r/tree/release/1.x": ("o", "r", "release/1.x"),
            "https://github.com/psf/requests-html": ("psf", "requests-html", None),
            "https://github.com/a/b.c_d": ("a", "b.c_d", None),
        }
        for url, (owner, repo, ref) in cases.items():
            parsed = parse_repo_url(url)
            self.assertEqual((parsed.owner, parsed.repo, parsed.ref), (owner, repo, ref), url)
            self.assertEqual(parsed.clone_url, f"https://github.com/{owner}/{repo}.git")

    def test_invalid_or_dangerous_urls(self) -> None:
        bad = [
            "https://gitlab.com/o/r",
            "https://github.com/o",
            "https://github.com/",
            "https://evil.com/github.com/o/r",
            "https://github.com.evil.com/o/r",
            "ssh://git@github.com/o/r",
            "git@github.com:o/r.git",
            "file:///etc/passwd",
            "/home/user/repo",
            "https://github.com/o/r?x=1",
            "https://github.com/o/r --upload-pack=evil",
            "https://github.com/o/r/tree/-x",
            "https://github.com/o/r/tree/../../etc",
            "https://github.com/-o/r",
            "https://github.com/o/..",
            "",
        ]
        for url in bad:
            with self.assertRaises(CloneError, msg=url):
                parse_repo_url(url)

    def test_directory_name_is_filesystem_safe(self) -> None:
        ref = parse_repo_url("https://github.com/o/r/tree/release/1.x")
        self.assertNotIn("/", ref.dir_name)


# ---------------------------------------------------------------- cloning with a fake git
class FakeGit:
    """Stands in for subprocess.run: records the call and mimics git's outcome."""

    def __init__(self, returncode: int = 0, stderr: str = "", raises: Exception | None = None) -> None:
        self.returncode, self.stderr, self.raises = returncode, stderr, raises
        self.calls: list[tuple[list[str], dict]] = []

    def __call__(self, cmd, **kwargs):
        self.calls.append((list(cmd), kwargs))
        if self.raises:
            raise self.raises
        target = Path(cmd[-1])
        if self.returncode == 0:
            (target / ".git").mkdir(parents=True)
            (target / "app.py").write_text("def hello():\n    return 'hi world from the repo'\n")
        else:
            target.mkdir(parents=True, exist_ok=True)  # git may leave a partial folder behind
        return subprocess.CompletedProcess(cmd, self.returncode, "", self.stderr)


@unittest.skipUnless(HAS_GIT, "git is not installed")
class CloneWithFakeGitTests(TempDirCase):
    def setUp(self) -> None:
        super().setUp()
        self.repos = self.tmp / "repos"
        self.ref = parse_repo_url("https://github.com/owner/repo")

    def clone(self, runner, **kw):
        return clone_repo(self.ref, self.repos, timeout_s=30, runner=runner, **kw)

    def test_safe_command_line(self) -> None:
        fake = FakeGit()
        dest = self.clone(fake)
        cmd, kwargs = fake.calls[0]
        self.assertEqual(cmd[0], "git")
        self.assertIn("--depth", cmd)
        self.assertEqual(cmd[cmd.index("--depth") + 1], "1")
        self.assertIn("core.symlinks=false", cmd)
        self.assertEqual(cmd[-3], "--")  # URL comes after "--": it can never act as an option
        self.assertEqual(cmd[-2], "https://github.com/owner/repo.git")
        self.assertEqual(kwargs["timeout"], 30)
        self.assertEqual(kwargs["env"]["GIT_TERMINAL_PROMPT"], "0")
        self.assertNotIn("shell", kwargs)
        self.assertEqual(dest, self.repos / "owner__repo")
        self.assertTrue((dest / "app.py").exists())
        self.assertFalse((self.repos / "owner__repo.partial").exists())

    def test_branch_is_passed(self) -> None:
        self.ref = parse_repo_url("https://github.com/owner/repo/tree/dev")
        fake = FakeGit()
        self.clone(fake)
        cmd = fake.calls[0][0]
        self.assertEqual(cmd[cmd.index("--branch") + 1], "dev")

    def test_existing_clone_is_reused(self) -> None:
        self.clone(FakeGit())
        fake = FakeGit()
        self.clone(fake)
        self.assertEqual(fake.calls, [])  # no second download

    def test_refresh_replaces_clone(self) -> None:
        dest = self.clone(FakeGit())
        (dest / "stale.txt").write_text("old")
        fake = FakeGit()
        self.clone(fake, refresh=True)
        self.assertEqual(len(fake.calls), 1)
        self.assertFalse((dest / "stale.txt").exists())

    def test_failed_refresh_keeps_old_clone(self) -> None:
        dest = self.clone(FakeGit())
        with self.assertRaises(CloneError):
            self.clone(FakeGit(128, "fatal: unable to access: Could not resolve host"), refresh=True)
        self.assertTrue((dest / "app.py").exists())

    def test_not_found_message(self) -> None:
        fake = FakeGit(128, "fatal: repository 'https://github.com/owner/repo.git/' not found")
        with self.assertRaises(CloneError) as ctx:
            self.clone(fake)
        self.assertIn("private", str(ctx.exception))
        self.assertFalse((self.repos / "owner__repo.partial").exists())
        self.assertFalse((self.repos / "owner__repo").exists())

    def test_network_message(self) -> None:
        with self.assertRaises(CloneError) as ctx:
            self.clone(FakeGit(128, "fatal: unable to access '...': Could not resolve host: github.com"))
        self.assertIn("internet", str(ctx.exception))

    def test_timeout_cleans_up(self) -> None:
        fake = FakeGit(raises=subprocess.TimeoutExpired(cmd="git", timeout=30))
        with self.assertRaises(CloneError) as ctx:
            self.clone(fake)
        self.assertIn("longer than 30s", str(ctx.exception))
        self.assertEqual(list(self.repos.glob("*")), [])

    def test_git_missing(self) -> None:
        with self.assertRaises(CloneError) as ctx:
            clone_repo(self.ref, self.repos, timeout_s=5, git="definitely-not-installed-git-xyz")
        self.assertIn("Install git", str(ctx.exception))

    def test_folder_without_git_dir_is_not_trusted(self) -> None:
        (self.repos / "owner__repo").mkdir(parents=True)
        with self.assertRaises(CloneError):
            self.clone(FakeGit())


@unittest.skipUnless(HAS_GIT, "git is not installed")
class RealGitCloneTests(TempDirCase):
    def make_origin(self) -> Path:
        origin = self.tmp / "origin"
        origin.mkdir()
        write(origin, "main.py", "def run():\n    return 42\n")
        git = ["git", "-c", "user.email=t@example.com", "-c", "user.name=T"]
        subprocess.run([*git, "init", "-q", "-b", "main"], cwd=origin, check=True)
        subprocess.run([*git, "add", "."], cwd=origin, check=True)
        subprocess.run([*git, "commit", "-q", "-m", "init"], cwd=origin, check=True)
        return origin

    def test_real_shallow_clone(self) -> None:
        origin = self.make_origin()
        dest = self.tmp / "out" / "clone"
        run_git_clone(origin.as_uri(), dest, branch=None, timeout_s=60)
        self.assertEqual((dest / "main.py").read_text(), "def run():\n    return 42\n")
        self.assertTrue((dest / ".git").exists())

    def test_symlinks_are_not_created(self) -> None:
        origin = self.make_origin()
        try:
            os.symlink("/etc/passwd", origin / "link.txt")
        except (OSError, NotImplementedError):
            self.skipTest("cannot create symlinks here")
        git = ["git", "-c", "user.email=t@example.com", "-c", "user.name=T"]
        subprocess.run([*git, "add", "."], cwd=origin, check=True)
        subprocess.run([*git, "commit", "-q", "-m", "link"], cwd=origin, check=True)
        dest = self.tmp / "clone2"
        run_git_clone(origin.as_uri(), dest, branch=None, timeout_s=60)
        self.assertFalse(os.path.islink(dest / "link.txt"))  # a plain file, not a link out of the clone

    def test_unknown_branch(self) -> None:
        origin = self.make_origin()
        with self.assertRaises(CloneError) as ctx:
            run_git_clone(origin.as_uri(), self.tmp / "c3", branch="nope", timeout_s=60)
        self.assertIn("branch", str(ctx.exception).lower())


