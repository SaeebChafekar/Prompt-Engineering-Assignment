class CliTests(TempDirCase):
    def run_cli(self, *args: str) -> tuple[int, str, str]:
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = cli_main(list(args))
        return code, out.getvalue(), err.getvalue()

    def test_summary_and_dump(self) -> None:
        root = self.tmp / "proj"
        write(root, "app.py", SERVICE)
        write(root, "README.md", "# Title\n\nSome readme text that is worth indexing.\n")
        dump = self.tmp / "dump"
        code, out, _ = self.run_cli(str(root), "--out", str(dump), "--show-chunks", "2")
        self.assertEqual(code, 0)
        self.assertIn("Repository : proj", out)
        self.assertIn("Chunks", out)
        self.assertIn("--- ", out)
        summary = json.loads((dump / "summary.json").read_text())
        self.assertEqual(summary["files"], 2)
        chunks = [json.loads(line) for line in (dump / "chunks.jsonl").read_text().splitlines()]
        self.assertTrue(chunks and {"id", "text", "context", "start_line"} <= set(chunks[0]))
        self.assertTrue((dump / "files.json").exists() and (dump / "parsed_python.json").exists())

    def test_errors_return_exit_code_1(self) -> None:
        code, _, err = self.run_cli("definitely-not-a-folder-or-url")
        self.assertEqual(code, 1)
        self.assertIn("ERROR", err)


