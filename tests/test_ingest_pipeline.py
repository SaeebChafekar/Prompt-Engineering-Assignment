class PipelineTests(TempDirCase):
    def build_repo(self) -> Path:
        root = self.tmp / "myrepo"
        write(root, "README.md", "# My Repo\n\nThis project does useful things for people.\n\n## Usage\n\nRun it with the command line tool.\n")
        write(root, "src/service.py", SERVICE)
        write(root, "src/bad.py", "def broken(:\n    pass\n")
        write(root, "tests/test_service.py", "def test_handle():\n    assert 1 + 1 == 2, 'math works'\n")
        write(root, "config/settings.yaml", "debug: true\nport: 8080\n")
        write(root, "web/app.js", "export function start() { return 1; }\n")
        write(root, "crlf.py", "def windows():\r\n    return 'crlf'\r\n")
        # things that must be skipped
        write(root, "node_modules/lib/index.js", "module.exports = 1;\n")
        write(root, "build/gen.py", "x = 1\n")
        write(root, ".git/config", "[core]\n")
        write(root, ".env", "SECRET=1\n")
        write(root, "package-lock.json", "{}\n")
        write(root, "api_pb2.py", "x = 1\n")
        write(root, "image.png", b"\x89PNG\r\n\x1a\n\x00\x00")
        write(root, "binary.py", b"x = 1\x00\x00\x00")
        write(root, "empty.py", "")
        write(root, "blank.py", "\n\n  \n")
        write(root, "generated.py", "# DO NOT EDIT: generated file\nx = 1\n")
        write(root, "huge.py", "x = 1\n" * 100)
        return root

    def test_end_to_end(self) -> None:
        cfg = Config(data_dir=str(self.tmp / "data"), max_file_bytes=500)
        result = ingest_directory(self.build_repo(), cfg)
        paths = [f.path for f in result.files]
        self.assertEqual(
            paths,
            ["README.md", "config/settings.yaml", "crlf.py", "src/bad.py", "src/service.py", "tests/test_service.py", "web/app.js"],
        )
        self.assertEqual(result.repo_name, "myrepo")
        self.assertEqual(
            result.skipped,
            {
                "binary": 1, "empty": 2, "generated": 1, "hidden_file": 1, "ignored_file": 2,
                "ignored_folder": 3, "too_large": 1, "unsupported_type": 1,
            },
        )
        by_path = {f.path: f for f in result.files}
        self.assertTrue(by_path["tests/test_service.py"].is_test)
        self.assertFalse(by_path["src/service.py"].is_test)
        self.assertNotIn("\r", by_path["crlf.py"].text)  # line endings normalized

    def test_parsing_and_chunking_results(self) -> None:
        result = ingest_directory(self.build_repo(), Config(data_dir=str(self.tmp / "d"), max_file_bytes=500))
        parsed = {p.path: p for p in result.parsed}
        self.assertEqual(set(parsed), {"crlf.py", "src/bad.py", "src/service.py", "tests/test_service.py"})
        self.assertIsNotNone(parsed["src/bad.py"].error)
        self.assertIsNone(parsed["src/service.py"].error)
        self.assertTrue(any("could not be parsed" in w and "src/bad.py" in w for w in result.warnings))
        symbols = {c.symbol for c in result.chunks if c.symbol}
        self.assertIn("Service.handle", symbols)
        kinds = {c.kind for c in result.chunks}
        self.assertTrue({"function", "class", "doc", "config", "block"} <= kinds)
        bad = [c for c in result.chunks if c.path == "src/bad.py"]
        self.assertEqual([c.kind for c in bad], ["block"])  # fell back to plain chunking
        ids = [c.id for c in result.chunks]
        self.assertEqual(len(ids), len(set(ids)))
        self.assertIn("Chunks", result.summary())

    def test_include_tests_false(self) -> None:
        cfg = Config(data_dir=str(self.tmp / "d"), max_file_bytes=500, include_tests=False)
        result = ingest_directory(self.build_repo(), cfg)
        self.assertNotIn("tests/test_service.py", [f.path for f in result.files])
        self.assertEqual(result.skipped.get("test_file"), 1)

    def test_symlinks_are_not_followed(self) -> None:
        root = self.tmp / "linkrepo"
        write(root, "real.py", "def real():\n    return 'real code here'\n")
        outside = self.tmp / "outside"
        write(outside, "secret.py", "def secret():\n    return 'do not read me'\n")
        try:
            os.symlink(outside, root / "linked_dir")
            os.symlink(outside / "secret.py", root / "linked_file.py")
        except (OSError, NotImplementedError):
            self.skipTest("cannot create symlinks here")
        result = ingest_directory(root, self.cfg)
        self.assertEqual([f.path for f in result.files], ["real.py"])
        self.assertEqual(result.skipped.get("symlink"), 2)

    def test_empty_repo_warns(self) -> None:
        root = self.tmp / "nothing"
        write(root, "logo.png", b"\x89PNG\x00")
        result = ingest_directory(root, self.cfg)
        self.assertEqual(result.files, [])
        self.assertTrue(any("No indexable files" in w for w in result.warnings))

    def test_too_many_files(self) -> None:
        root = self.tmp / "many"
        for i in range(5):
            write(root, f"f{i}.py", f"def f{i}():\n    return {i} + 1000\n")
        with self.assertRaises(RepoTooLargeError) as ctx:
            ingest_directory(root, Config(max_repo_files=3))
        self.assertIn("CHATBOT_MAX_REPO_FILES", str(ctx.exception))

    def test_too_many_bytes(self) -> None:
        root = self.tmp / "heavy"
        for i in range(3):
            write(root, f"f{i}.py", "x = 1\n" * 1000)
        with self.assertRaises(RepoTooLargeError):
            ingest_directory(root, Config(max_repo_bytes=10_000, max_file_bytes=100_000))

    def test_time_limit(self) -> None:
        root = self.tmp / "slow"
        write(root, "a.py", "def a():\n    return 'something useful'\n")
        ticks = iter(range(0, 10_000, 100))  # the fake clock jumps 100s per reading
        with self.assertRaises(IngestError) as ctx:
            ingest_directory(root, Config(ingest_timeout_s=5), clock=lambda: float(next(ticks)))
        self.assertIn("exceeded", str(ctx.exception))

    def test_not_a_folder(self) -> None:
        with self.assertRaises(IngestError):
            ingest_directory(self.tmp / "missing", self.cfg)

    def test_empty_init_files_are_kept_because_they_mark_packages(self) -> None:
        root = self.tmp / "pkgrepo"
        write(root, "pkg/__init__.py", "")
        write(root, "pkg/empty_module.py", "")
        write(root, "pkg/real.py", "def real():\n    return 'something useful'\n")
        result = ingest_directory(root, self.cfg)
        self.assertEqual([f.path for f in result.files], ["pkg/__init__.py", "pkg/real.py"])
        self.assertEqual(result.skipped, {"empty": 1})
        self.assertEqual([c.path for c in result.chunks], ["pkg/real.py"])  # but it has no chunks

    def test_non_utf8_file_is_decoded_leniently(self) -> None:
        root = self.tmp / "latin"
        write(root, "old.py", "# caf\xe9\ndef f():\n    return 'latin one text'\n".encode("latin-1"))
        result = ingest_directory(root, self.cfg)
        self.assertEqual([f.path for f in result.files], ["old.py"])


